'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';

const navItems = [
  { label: 'Dashboard', href: '/', icon: LayoutIcon },
  { label: 'Portales', href: '/portals', icon: GlobeIcon },
  { label: 'Scout', href: '/scout', icon: SearchIcon },
  { label: 'Jobs', href: '/jobs', icon: ZapIcon },
  { label: 'Datos', href: '/data', icon: DatabaseIcon },
];

export function Sidebar() {
  const pathname = usePathname();

  return (
    <aside className="fixed inset-y-0 left-0 z-50 flex w-56 flex-col border-r border-border bg-card">
      <div className="flex h-14 items-center border-b border-border px-6">
        <Link href="/" className="text-lg font-bold tracking-tight text-foreground">
          DataMktMx
        </Link>
      </div>
      <nav className="flex-1 space-y-1 px-3 py-4">
        {navItems.map((item) => {
          const isActive = item.href === '/' ? pathname === '/' : pathname.startsWith(item.href);
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 rounded-md px-3 py-2 text-sm font-medium transition-colors ${
                isActive
                  ? 'bg-accent text-accent-foreground'
                  : 'text-muted-foreground hover:bg-accent hover:text-accent-foreground'
              }`}
            >
              <item.icon className="h-4 w-4" />
              {item.label}
            </Link>
          );
        })}
      </nav>
      <div className="border-t border-border px-6 py-3">
        <p className="text-xs text-muted-foreground">Admin Dashboard</p>
      </div>
    </aside>
  );
}

